"""Write paper/numbers.tex: one LaTeX macro per number quoted in the paper,
read from the analysis outputs (ground rule: no hand-typed numbers). Results
that don't exist yet render as a red TBD so they can't slip through.

Usage: python -m analysis.paper_numbers
"""
import json
from pathlib import Path

import pandas as pd

OUT = Path("paper/numbers.tex")
M = {"DF": "df", "F2F": "ff", "FS": "fs", "NT": "nt"}
macros = {}


def put(name, value, fmt="{:.2f}"):
    assert name.isalpha(), name
    macros[name] = fmt.format(value) if isinstance(value, (int, float)) else str(value)


def ci(lo, hi, fmt="{:.2f}"):
    return f"[{fmt.format(lo)}, {fmt.format(hi)}]"


def opt_csv(path):
    p = Path(path)
    return pd.read_csv(p) if p.exists() else None


cur = pd.read_csv("analysis/cross_manipulation_xception.csv", index_col=0)
curv = pd.read_csv("analysis/cross_manipulation_cnn_vit.csv", index_col=0)
for a in M:
    for b in M:
        put(f"cur{M[a]}{M[b]}", float(cur.loc[a, b]))
        put(f"curvit{M[a]}{M[b]}", float(curv.loc[a, b]))
base = pd.read_csv("analysis/baseline_comparison.csv").set_index("model")
put("baseauxc", float(base.loc["xception", "video_auc"]), "{:.3f}")
put("baseauvit", float(base.loc["cnn_vit", "video_auc"]), "{:.3f}")
arch = json.loads(Path("analysis/architecture_correlation.json").read_text())
put("archr", arch["pearson_r"]); put("archrho", arch["spearman_r"])

g = pd.read_csv("analysis/reference/gate1_seed_mean_ci.csv").set_index(["train", "test"])
for (a, b), r in g.iterrows():
    put(f"ref{M[a]}{M[b]}", r["seed_mean_auc"])
    put(f"ref{M[a]}{M[b]}ci", ci(r["ci95_lo"], r["ci95_hi"]))
diffs = [abs(g.loc[(a, b), "seed_mean_auc"] - float(cur.loc[a, b])) for a, b in g.index]
put("refmaxdiff", max(diffs))

e = pd.read_csv("analysis/phase3/effect_sizes.csv")
for pl, tag in [("current", "cur"), ("reference", "ref")]:
    s = e[(e["stat"] == "hf_ratio") & (e["pipeline"] == pl)].set_index("method")
    for mth in M:
        put(f"hf{tag}{M[mth]}", s.loc[mth, "d"])
        put(f"hf{tag}{M[mth]}ci", ci(s.loc[mth, "d_ci_lo"], s.loc[mth, "d_ci_hi"]))
        put(f"hf{tag}{M[mth]}paired", s.loc[mth, "d_paired"])
sp = pd.read_csv("analysis/phase3/sign_prediction.csv")
sp = sp[sp["stat"] == "hf_ratio"].set_index("matrix")
for key, tag in [("current_xception", "xc"), ("current_cnn_vit", "vit"), ("reference_xception", "ref")]:
    put(f"sprho{tag}", sp.loc[key, "spearman_rho"])
    put(f"spp{tag}", sp.loc[key, "perm_p_rho"], "{:.3f}")
    put(f"spcorrect{tag}", f"{int(sp.loc[key, 'cells_correct'])}/{int(sp.loc[key, 'cells_scored'])}")
rel = pd.read_csv("analysis/phase3/reliance_reference.csv").set_index(["train", "stat"])
for stat, tag in [("lap_var", "lap"), ("noise_std", "noise"), ("hf_ratio", "hf"), ("boundary_grad", "bound")]:
    put(f"rel{tag}df", rel.loc[("DF", stat), "rho_prob_vs_stat_on_reals"])
    put(f"relp{tag}df", rel.loc[("DF", stat), "p_value"], "{:.3f}")
    put(f"rel{tag}fs", rel.loc[("FS", stat), "rho_prob_vs_stat_on_reals"])
    put(f"relp{tag}fs", rel.loc[("FS", stat), "p_value"], "{:.2f}")

pub = pd.read_csv("analysis/external/facexray_table1_xception.csv", index_col=0)
for a, b in [("DF", "FS"), ("NT", "FS"), ("FS", "DF"), ("FS", "NT")]:
    put(f"pub{M[a]}{M[b]}", float(pub.loc[a, b]))
pubp = pd.read_csv("analysis/external/sign_prediction_published.csv").iloc[0]
put("pubrho", pubp["spearman_rho"]); put("pubp", pubp["perm_p"], "{:.3f}")
aug = pd.read_csv("analysis/phase4/hf_aug_check.csv").set_index(["method", "condition"])
put("augdfbefore", aug.loc[("Deepfakes", "no augmentation"), "d_hf_ratio_vs_real"])
put("augdfafter", aug.loc[("Deepfakes", "RandomBlurSharpen"), "d_hf_ratio_vs_real"])
put("augfsbefore", aug.loc[("FaceSwap", "no augmentation"), "d_hf_ratio_vs_real"])
put("augfsafter", aug.loc[("FaceSwap", "RandomBlurSharpen"), "d_hf_ratio_vs_real"])

d4 = opt_csv("analysis/phase4/delta_vs_phase1.csv")
for a, b in [("DF", "DF"), ("DF", "FF"), ("DF", "FS"), ("DF", "NT"), ("FS", "DF"), ("FS", "FF"), ("FS", "FS"), ("FS", "NT")]:
    a_, b_ = ("F2F" if a == "FF" else a), ("F2F" if b == "FF" else b)
    row = None if d4 is None else d4[(d4["train"] == a_) & (d4["test"] == b_)]
    key = f"{M[a_]}{M[b_]}"
    if row is not None and len(row) and int(row["n_seeds_phase4"].iloc[0]) == 3:
        r = row.iloc[0]
        put(f"augauc{key}", r["phase4_auc"]); put(f"augauc{key}ci", ci(r["phase4_ci_lo"], r["phase4_ci_hi"]))
        put(f"augdelta{key}", r["delta"], "{:+.3f}")
        put(f"augdelta{key}ci", ci(r["delta_ci_lo"], r["delta_ci_hi"], "{:+.3f}"))
    else:
        for k in ["augauc", "augauc*ci", "augdelta", "augdelta*ci"]:
            macros[k.replace("*", key) if "*" in k else f"{k}{key}"] = r"\pending"

OUT.parent.mkdir(exist_ok=True)
lines = ["% Generated by analysis/paper_numbers.py -- do not edit by hand.",
         r"\providecommand{\pending}{\textcolor{red}{\textbf{TBD}}}"]
lines += [rf"\newcommand{{\{k}}}{{{v}}}" for k, v in sorted(macros.items())]
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {OUT}: {len(macros)} macros, {sum(v == chr(92) + 'pending' for v in macros.values())} pending")
